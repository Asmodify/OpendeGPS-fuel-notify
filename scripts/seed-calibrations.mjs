// Copies the tank calibration tables from the local calibrations.json into the cloud database
// (table fuel.calibrations), one [[mV, litres], ...] table per tracker IMEI.
//
//   npm install                                   (once: installs the Postgres client)
//   DATABASE_URL=postgresql://... node scripts/seed-calibrations.mjs [calibrations.json]
//   node scripts/seed-calibrations.mjs [calibrations.json] --sql > seed.sql
//                                                 (prints SQL instead, e.g. for the Supabase SQL editor)
//
// Existing rows for the same IMEIs are replaced; others are left alone.
import path from 'node:path';
import { loadCalibrations, ROOT_DIR } from '../src/config.js';

const args = process.argv.slice(2);
const printSql = args.includes('--sql');
const file = path.resolve(args.find((a) => !a.startsWith('--')) || path.join(ROOT_DIR, 'calibrations.json'));
const cal = loadCalibrations(file);
if (cal.error) {
  console.error(cal.error);
  process.exit(1);
}
const rows = Object.entries(cal.vehicles).map(([imei, c]) => ({ imei, points: c.table }));
if (!rows.length) {
  console.error(`No usable calibration tables in ${file}`);
  process.exit(1);
}

if (printSql) {
  const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;
  console.log('-- tank calibration tables (generated by scripts/seed-calibrations.mjs; contains tracker IMEIs: do not commit)');
  console.log('insert into fuel.calibrations (imei, points) values');
  console.log(rows.map((r) => `  (${lit(r.imei)}, ${lit(JSON.stringify(r.points))}::jsonb)`).join(',\n'));
  console.log('on conflict (imei) do update set points = excluded.points, updated_at = now();');
  process.exit(0);
}

if (!process.env.DATABASE_URL) {
  console.error('Set DATABASE_URL (or use --sql to print the SQL instead).');
  process.exit(2);
}
const { getSql } = await import('../src/cloud/pg.js');
const sql = getSql();
try {
  const r = await sql`insert into fuel.calibrations (imei, points)
    select imei, points from jsonb_to_recordset(${JSON.stringify(rows)}::jsonb) as x(imei text, points jsonb)
    on conflict (imei) do update set points = excluded.points, updated_at = now()`;
  console.log(`Saved calibration tables for ${r.count} vehicles.`);
} finally {
  await sql.end({ timeout: 5 });
}
